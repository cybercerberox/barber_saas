-- ==========================================================================
-- SCRIPT SQL COMPLETO: MICRO-SAAS BARBEARIAS (MULTI-TENANT)
-- Supabase PostgreSQL + Row Level Security (RLS)
-- ==========================================================================
-- Execute este script no SQL Editor do seu projeto Supabase.

-- 1. Habilitar extensão pgcrypto (UUID)
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Limpar estrutura anterior
DROP TABLE IF EXISTS public.agendamentos CASCADE;
DROP TABLE IF EXISTS public.servicos CASCADE;
DROP TABLE IF EXISTS public.barbearias CASCADE;

-- ==========================================================================
-- TABELA 1: BARBEARIAS (Tenants do SaaS)
-- ==========================================================================
CREATE TABLE public.barbearias (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    nome_salao TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX idx_barbearias_slug ON public.barbearias (slug);
CREATE INDEX idx_barbearias_owner_id ON public.barbearias (owner_id);

-- ==========================================================================
-- TABELA 2: SERVIÇOS (Personalizados por cada barbearia)
-- ==========================================================================
CREATE TABLE public.servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbearia_id UUID NOT NULL REFERENCES public.barbearias(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    descricao TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX idx_servicos_barbearia_id ON public.servicos (barbearia_id);

-- ==========================================================================
-- TABELA 3: AGENDAMENTOS (Clientes e Horários por Barbearia)
-- ==========================================================================
CREATE TABLE public.agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbearia_id UUID NOT NULL REFERENCES public.barbearias(id) ON DELETE CASCADE,
    nome_cliente TEXT NOT NULL,
    telefone TEXT NOT NULL,
    servico TEXT NOT NULL,
    data_agendamento DATE NOT NULL,
    hora TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'concluido', 'cancelado')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX idx_agendamentos_barbearia_id ON public.agendamentos (barbearia_id);
CREATE INDEX idx_agendamentos_data ON public.agendamentos (data_agendamento);
CREATE INDEX idx_agendamentos_status ON public.agendamentos (status);

-- ==========================================================================
-- HABILITAR ROW LEVEL SECURITY (RLS)
-- ==========================================================================
ALTER TABLE public.barbearias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.servicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.agendamentos ENABLE ROW LEVEL SECURITY;

-- ==========================================================================
-- POLÍTICAS RLS: BARBEARIAS
-- ==========================================================================

-- Leitura pública por slug (para carregar index.html?salao=vintage)
CREATE POLICY "Permitir leitura pública de barbearias por slug"
ON public.barbearias FOR SELECT
TO anon, authenticated
USING (true);

-- Donos podem cadastrar sua barbearia
CREATE POLICY "Donos podem cadastrar sua barbearia"
ON public.barbearias FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = owner_id);

-- Donos podem atualizar sua barbearia
CREATE POLICY "Donos podem atualizar sua barbearia"
ON public.barbearias FOR UPDATE
TO authenticated
USING (auth.uid() = owner_id)
WITH CHECK (auth.uid() = owner_id);

-- Donos podem deletar sua barbearia
CREATE POLICY "Donos podem deletar sua barbearia"
ON public.barbearias FOR DELETE
TO authenticated
USING (auth.uid() = owner_id);

-- ==========================================================================
-- POLÍTICAS RLS: SERVIÇOS
-- ==========================================================================

-- Qualquer pessoa na página pública pode ler os serviços da barbearia
CREATE POLICY "Permitir leitura pública de servicos"
ON public.servicos FOR SELECT
TO anon, authenticated
USING (true);

-- Donos cadastram serviços para sua própria barbearia
CREATE POLICY "Donos cadastram servicos em sua barbearia"
ON public.servicos FOR INSERT
TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.barbearias
        WHERE public.barbearias.id = public.servicos.barbearia_id
          AND public.barbearias.owner_id = auth.uid()
    )
);

-- Donos atualizam serviços de sua barbearia
CREATE POLICY "Donos atualizam servicos de sua barbearia"
ON public.servicos FOR UPDATE
TO authenticated
