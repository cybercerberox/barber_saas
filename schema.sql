-- Qualquer cliente pode agendar (Atenção: no PostgreSQL, INSERT exige WITH CHECK, não USING)
CREATE POLICY "Permitir inserção pública de agendamentos"
ON public.agendamentos FOR INSERT
TO anon, authenticated
WITH CHECK (true);

